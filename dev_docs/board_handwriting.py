#!/usr/bin/env python3
"""Turn the freehand strokes of a Merv board export into the inline SVGs the set-up page draws.

  python3 dev_docs/board_handwriting.py <elements.json> > merv-typescript/packages/scope/src/connect-handwriting.ts

<elements.json> is the board's board_elements records (an array of Excalidraw elements). Each
named piece is the strokes inside a box of board coordinates; the output is one SVG per piece,
in currentColor, with its viewBox at the strokes' own bounds.
"""
import json, sys

PIECES = {  # name: (x0, y0, x1, y1) in board units, from board.read get of the Welcome board
    'title': (530, 80, 1300, 190),
    'install': (300, 240, 800, 360),
    'claude': (310, 385, 540, 450),
    'codex': (310, 510, 520, 590),
    'rule1': (390, 640, 1350, 675),
    'terminal': (320, 700, 560, 785),
    'rule2': (400, 995, 1350, 1030),
    'tryit': (315, 1045, 500, 1135),
    'lookatit': (565, 1205, 1000, 1310),
}

def main(path):
    els = [e for e in json.load(open(path)) if e.get('type') == 'freedraw' and not e.get('isDeleted')]
    out = ['// Generated by dev_docs/board_handwriting.py from the project Welcome board; do not edit by hand.',
           '/** The founder\'s handwriting, one inline SVG per label, drawn in currentColor. */',
           'export const handwriting = {']
    for name, (x0, y0, x1, y1) in PIECES.items():
        strokes = [e for e in els if x0 <= e['x'] <= x1 and y0 <= e['y'] <= y1]
        if not strokes:
            raise SystemExit(f'no strokes for {name}')
        paths, xs, ys = [], [], []
        for e in strokes:
            pts = [(e['x'] + p[0], e['y'] + p[1]) for p in e['points']]
            pts = pts[::2] if len(pts) > 12 else pts
            xs += [p[0] for p in pts]; ys += [p[1] for p in pts]
            d = 'M' + 'L'.join(f'{x:.1f} {y:.1f}' for x, y in pts)
            paths.append((d, e.get('strokeWidth', 2) * 2.4))
        pad = 4
        bx, by, bw, bh = min(xs) - pad, min(ys) - pad, max(xs) - min(xs) + 2 * pad, max(ys) - min(ys) + 2 * pad
        body = ''.join(f'<path d="{d}" stroke-width="{w:.1f}"/>' for d, w in paths)
        svg = (f'<svg viewBox="{bx:.1f} {by:.1f} {bw:.1f} {bh:.1f}" fill="none" stroke="currentColor" '
               f'stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">{body}</svg>')
        out.append(f'  {name}: {json.dumps(svg)},')
    out.append('} as const;')
    print('\n'.join(out))

main(sys.argv[1])
